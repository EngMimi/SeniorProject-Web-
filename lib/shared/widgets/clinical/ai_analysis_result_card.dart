/// Presents the AI analysis result of a test, for any modality.
///
/// All three models (Voice, Spiral Drawing, MRI) are live, so a test with a
/// result shows the real model output. The placeholder below only shows for
/// an older test record that predates whichever model analyzed it.
class AiAnalysisResultCard extends StatelessWidget {
  const AiAnalysisResultCard({super.key, required this.test});

  final ClinicalTest test;

  @override
  Widget build(BuildContext context) {
    return SectionCard(
      title: 'AI Analysis Result',
      subtitle: '${test.modality.analysisTitle} · generated by the AI model',
      icon: Icons.analytics_outlined,
      color: AppColors.aiSurface,
      borderColor: AppColors.aiBorder,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        spacing: AppSpacing.lg,
        children: [
          const ClinicalNotice(),
          // Shows the actual uploaded image (spiral drawing photo or MRI
          // scan) when one was saved, so the doctor can look at it
          // directly rather than only seeing the AI's prediction text.
          if (test.fileUrl != null) _UploadedImagePreview(url: test.fileUrl!),
          if (test.status.hasResult) ...[
            InfoGrid(
              minFieldWidth: 160,
              fields: [
                const InfoField(label: 'Analysis', value: 'Completed'),
                InfoField(label: 'Modality', value: test.modality.label),
                InfoField(
                  label: 'Completed on',
                  value: test.analysisCompletedOn == null
                      ? '—'
                      : formatDate(test.analysisCompletedOn!),
                ),
                InfoField(
                  label: 'Result status',
                  child: AnalysisStatusBadge(status: test.status),
                ),
              ],
            ),
            if (test.hasAiResult)
              _AiModelOutput(test: test)
            else
              _ModelOutputPlaceholder(modality: test.modality),
          ] else
            _NoResultYet(status: test.status),
        ],
      ),
    );
  }
}

/// Shown instead of a result when the AI hasn't finished analyzing yet.
class _NoResultYet extends StatelessWidget {
  const _NoResultYet({required this.status});

  final AnalysisStatus status;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final message = status == AnalysisStatus.processing
        ? 'The AI analysis for this test is in progress. The result will '
              'appear here when it is complete.'
        : 'The AI analysis for this test has not started yet.';

    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        AnalysisStatusBadge(status: status),
        const SizedBox(width: AppSpacing.md),
        Expanded(
          child: Text(
            message,
            style: theme.textTheme.bodyMedium?.copyWith(
              color: theme.colorScheme.onSurfaceVariant,
            ),
          ),
        ),
      ],
    );
  }
}

/// Real output of a live model (Voice or Spiral Drawing today): the
/// predicted class and the predicted probability of Parkinson's disease.
class _AiModelOutput extends StatelessWidget {
  const _AiModelOutput({required this.test});

  final ClinicalTest test;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isPd = test.aiPredictionCode == 1;
    final probability = test.aiProbabilityPd;
    final sampleNoun = switch (test.modality) {
      TestModality.voice => 'voice sample',
      TestModality.spiral => 'spiral drawing',
      TestModality.mri => 'scan',
    };

    return DecoratedBox(
      decoration: BoxDecoration(
        color: AppColors.surface,
        border: Border.all(color: AppColors.aiBorder),
        borderRadius: AppRadius.mdAll,
      ),
      child: Padding(
        padding: const EdgeInsets.all(AppSpacing.md),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          spacing: AppSpacing.md,
          children: [
            Text(
              '${test.modality.label} model output',
              style: theme.textTheme.titleSmall?.copyWith(
                fontWeight: FontWeight.w600,
              ),
            ),
            InfoGrid(
              minFieldWidth: 160,
              fields: [
                InfoField(
                  label: 'Prediction',
                  value: test.aiPrediction ?? '—',
                ),
                InfoField(
                  label: 'Probability of PD',
                  value: probability == null
                      ? '—'
                      : '${(probability * 100).toStringAsFixed(1)}%',
                ),
              ],
            ),
            Text(
              isPd
                  ? 'The model flagged indicators consistent with Parkinson’s '
                        'disease in this $sampleNoun.'
                  : 'The model did not flag indicators consistent with '
                        'Parkinson’s disease in this $sampleNoun.',
              style: theme.textTheme.bodySmall?.copyWith(
                color: theme.colorScheme.onSurfaceVariant,
              ),
            ),
          ],
        ),
      ),
    );
  }
}

